# Writes one home screen widget per Gallery design.
#
# A launcher will only place a widget it has a provider declared for, so a design that
# is to sit on the home screen on its own terms needs one of its own. Sharing a provider
# between every design of a size does not work: the design would have to be remembered
# somewhere outside the widget, and the second one placed would change the first.
#
# Forty-odd of anything is not a thing to write by hand, so the receivers, their provider
# files, their labels and the manifest entries are all generated from the catalogue the
# import script writes. Re-run this after `import_gallery_assets.ps1`.

param(
    [string]$Root = "C:\Users\leejm\AndroidStudioProjects\VisionWidget\app\src\main"
)

$ErrorActionPreference = "Stop"

$catalog = Get-Content (Join-Path $Root "assets\gallery\catalog.json") -Encoding UTF8 -Raw |
    ConvertFrom-Json

# `01-date-silk` -> `Gallery01DateSilk`
function Base-Name($id) {
    $parts = $id -split '-' | ForEach-Object {
        if ($_.Length -gt 0) { $_.Substring(0, 1).ToUpper() + $_.Substring(1) } else { $_ }
    }
    return "Gallery" + ($parts -join '')
}

function Class-Name($id) { return (Base-Name $id) + "Receiver" }

# Each design needs a widget class of its own, not just a receiver: Glance knows a widget
# by its class, and forty-four designs sharing one leaves it unable to tell them apart.
function Widget-Name($id) { return (Base-Name $id) + "Widget" }

$utf8 = New-Object System.Text.UTF8Encoding $false

# ---- receivers ---------------------------------------------------------------
$kt = New-Object System.Text.StringBuilder
[void]$kt.AppendLine("package app.visionov.visionwidget.widget")
[void]$kt.AppendLine("")
[void]$kt.AppendLine("import androidx.glance.appwidget.GlanceAppWidget")
[void]$kt.AppendLine("import app.visionov.visionwidget.ui.gallery.GalleryWidget")
[void]$kt.AppendLine("")
[void]$kt.AppendLine("/**")
[void]$kt.AppendLine(" * One widget class and one receiver per Gallery design.")
[void]$kt.AppendLine(" *")
[void]$kt.AppendLine(" * Generated by `tools/generate_gallery_widgets.ps1` — edit that, not this.")
[void]$kt.AppendLine(" *")
[void]$kt.AppendLine(" * A design needs a provider of its own for the launcher to place it, and a widget")
[void]$kt.AppendLine(" * class of its own for Glance to tell it apart: Glance goes by the class, so designs")
[void]$kt.AppendLine(" * sharing one cannot be redrawn separately. Between them that is what lets two clocks")
[void]$kt.AppendLine(" * sit side by side, each showing its own face and its own time.")
[void]$kt.AppendLine(" */")
[void]$kt.AppendLine("")

foreach ($w in $catalog.widgets) {
    [void]$kt.AppendLine("class $(Widget-Name $w.id) : GalleryDesignWidget(`"$($w.id)`")")
    [void]$kt.AppendLine("class $(Class-Name $w.id) : GalleryWidgetReceiver($(Widget-Name $w.id)())")
}

[void]$kt.AppendLine("")
[void]$kt.AppendLine("/** The receiver that puts [design] up, for the shelf's own add control. */")
[void]$kt.AppendLine("fun receiverFor(design: GalleryWidget): Class<*> = when (design.id) {")
foreach ($w in $catalog.widgets) {
    [void]$kt.AppendLine("    `"$($w.id)`" -> $(Class-Name $w.id)::class.java")
}
[void]$kt.AppendLine("    else -> $(Class-Name $catalog.widgets[0].id)::class.java")
[void]$kt.AppendLine("}")
[void]$kt.AppendLine("")
[void]$kt.AppendLine("/** The widget that draws [design], for anything asking it to redraw. */")
[void]$kt.AppendLine("fun widgetFor(design: GalleryWidget): GlanceAppWidget = when (design.id) {")
foreach ($w in $catalog.widgets) {
    [void]$kt.AppendLine("    `"$($w.id)`" -> $(Widget-Name $w.id)()")
}
[void]$kt.AppendLine("    else -> $(Widget-Name $catalog.widgets[0].id)()")
[void]$kt.AppendLine("}")

[System.IO.File]::WriteAllText(
    (Join-Path $Root "java\com\example\visionwidget\widget\GalleryWidgetReceivers.kt"),
    $kt.ToString(), $utf8)

# ---- provider files ----------------------------------------------------------
foreach ($w in $catalog.widgets) {
    $res = $w.resourceName
    if (-not $res) { $res = ($w.id -replace '-', '_').ToLower() }

    if ($w.size -eq "medium") {
        $minWidth = "250dp"; $cellWidth = 4
    } else {
        $minWidth = "110dp"; $cellWidth = 2
    }

    $xml = @"
<?xml version="1.0" encoding="utf-8"?>
<!--
  $($w.name) — generated by tools/generate_gallery_widgets.ps1.

  Not resizable, like the rest: a design is a drawing with a proportion of its own, and
  dragging it about can only take it further from the tile it was picked from.

  The preview is what the picker shows before the widget is placed, and it has to be a
  static image — so it is painted from the real design at the one moment every preview
  is shown at, which is the moment the shelf shows too. Re-export with PreviewExport.
-->
<appwidget-provider xmlns:android="http://schemas.android.com/apk/res/android"
    android:minWidth="$minWidth"
    android:minHeight="110dp"
    android:targetCellWidth="$cellWidth"
    android:targetCellHeight="2"
    android:updatePeriodMillis="1800000"
    android:resizeMode="none"
    android:widgetCategory="home_screen"
    android:previewImage="@drawable/preview_gallery_$res"
    android:initialLayout="@layout/vision_widget_loading" />
"@
    [System.IO.File]::WriteAllText(
        (Join-Path $Root "res\xml\gallery_$res`_widget_info.xml"), $xml, $utf8)
}

# ---- labels ------------------------------------------------------------------
$labels = New-Object System.Text.StringBuilder
[void]$labels.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$labels.AppendLine('<!-- Generated by tools/generate_gallery_widgets.ps1 — edit that, not this. -->')
[void]$labels.AppendLine('<resources>')
foreach ($w in $catalog.widgets) {
    $res = $w.resourceName
    if (-not $res) { $res = ($w.id -replace '-', '_').ToLower() }
    # The name is the designer's, and carries a middle dot that XML is happy with but
    # Android's string escaping is not asked to interpret.
    $safe = $w.name -replace '&', '&amp;' -replace '<', '&lt;' -replace "'", "\'"
    [void]$labels.AppendLine("    <string name=`"gallery_label_$res`">$safe</string>")
}
[void]$labels.AppendLine('</resources>')
[System.IO.File]::WriteAllText(
    (Join-Path $Root "res\values\gallery_widget_labels.xml"), $labels.ToString(), $utf8)

# ---- manifest ----------------------------------------------------------------
# Written between markers so the rest of the manifest is left alone.
$block = New-Object System.Text.StringBuilder
[void]$block.AppendLine("        <!-- GALLERY-WIDGETS:BEGIN generated by tools/generate_gallery_widgets.ps1 -->")
foreach ($w in $catalog.widgets) {
    $res = $w.resourceName
    if (-not $res) { $res = ($w.id -replace '-', '_').ToLower() }
    [void]$block.AppendLine("        <receiver")
    [void]$block.AppendLine("            android:name=`".widget.$(Class-Name $w.id)`"")
    [void]$block.AppendLine("            android:exported=`"false`"")
    [void]$block.AppendLine("            android:label=`"@string/gallery_label_$res`">")
    [void]$block.AppendLine("            <intent-filter>")
    [void]$block.AppendLine("                <action android:name=`"android.appwidget.action.APPWIDGET_UPDATE`" />")
    [void]$block.AppendLine("            </intent-filter>")
    [void]$block.AppendLine("            <meta-data")
    [void]$block.AppendLine("                android:name=`"android.appwidget.provider`"")
    [void]$block.AppendLine("                android:resource=`"@xml/gallery_$res`_widget_info`" />")
    [void]$block.AppendLine("        </receiver>")
}
[void]$block.Append("        <!-- GALLERY-WIDGETS:END -->")

$manifestPath = Join-Path $Root "AndroidManifest.xml"
$manifest = Get-Content $manifestPath -Encoding UTF8 -Raw
$pattern = '(?s)[ \t]*<!-- GALLERY-WIDGETS:BEGIN.*?GALLERY-WIDGETS:END -->'
if ($manifest -match $pattern) {
    $manifest = [regex]::Replace($manifest, $pattern, $block.ToString())
} else {
    $manifest = $manifest -replace '(\s*)</application>', ("`r`n" + $block.ToString() + "`r`n`r`n    </application>")
}
[System.IO.File]::WriteAllText($manifestPath, $manifest, $utf8)

"receivers : {0}" -f $catalog.widgets.Count
"providers : {0} xml" -f $catalog.widgets.Count
"labels    : res/values/gallery_widget_labels.xml"
"manifest  : block rewritten"
